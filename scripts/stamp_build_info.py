#!/usr/bin/env python3
"""Stamp per-component build commits into generated modules.

The rolling release tag changes on every main push, but the app and the peer
agent usually did NOT both change. Comparing a component's own build commit
to the newest release's manifest commit tells us whether that component
actually needs an update — so app-only releases stop nagging every agent and
agent-only releases stop nagging the app.

CI computes the commits with `git log -1 --format=%H -- <component paths>`
(full history checkout) and passes them via env. The generated modules are
git-ignored; local source runs fall back to computing the commit at runtime.
"""
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP_BUILD = ROOT / "src" / "build_info.py"
AGENT_BUILD = ROOT / "peer_agent" / "llama_peer_agent" / "build_info.py"


def _clean(value):
    value = (value or "").strip()
    return value if re.fullmatch(r"[0-9a-fA-F]{7,40}", value) else ""


def main() -> int:
    version = (os.environ.get("VERSION") or "").strip()
    app_commit = _clean(os.environ.get("APP_COMMIT"))
    agent_commit = _clean(os.environ.get("AGENT_COMMIT"))
    if not version:
        raise SystemExit("VERSION is required")

    APP_BUILD.write_text(
        '"""Generated by scripts/stamp_build_info.py (git-ignored)."""\n\n'
        f'RELEASE_VERSION = "{version}"\n'
        f'APP_COMMIT = "{app_commit}"\n'
        f'AGENT_COMMIT = "{agent_commit}"\n',
        encoding="utf-8")
    AGENT_BUILD.write_text(
        '"""Generated by scripts/stamp_build_info.py (git-ignored)."""\n\n'
        f'RELEASE_VERSION = "{version}"\n'
        f'AGENT_COMMIT = "{agent_commit}"\n',
        encoding="utf-8")
    print(f"stamped build info {version}: app={app_commit[:12] or '-'} "
          f"agent={agent_commit[:12] or '-'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
